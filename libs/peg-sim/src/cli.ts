import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { SCENARIOS } from './lib/scenarios';
import { runGrid } from './lib/run';
import { coverageTable, markdownSummary } from './lib/report';
import { looperGrid, looperSummary } from './lib/looperReport';

/**
 * Runs the full scenario grid and writes:
 *   out/results.json  every run's metrics and daily series
 *   out/<scenario>.csv one CSV per scenario (seed 1) for charting
 *   out/summary.md     the table the parameter decision is made from
 *
 * Deterministic: the same seeds produce the same files.
 *
 * With `--loopers` it runs only the leverage-looper scenarios and their paired
 * baselines, writes out/loopers.{md,json} and leaves RESULTS.md alone.
 */
const outDir = join(__dirname, '..', 'out');
mkdirSync(outDir, { recursive: true });

const seeds = [1, 2, 3, 4, 5];

// nx forwards `--loopers` as written, so `--loopers=false` must not select looper mode.
const looperFlag = process.argv.slice(2).find((a) => a === '--loopers' || a.startsWith('--loopers='));
if (looperFlag === '--loopers' || looperFlag === '--loopers=true') {
	const grid = looperGrid(seeds);
	writeFileSync(
		join(outDir, 'loopers.json'),
		JSON.stringify(grid.results.map((r) => ({ scenario: r.scenario, seed: r.seed, metrics: r.metrics, system: r.system, loopers: r.loopers })), null, 2)
	);
	const looperMd = looperSummary(grid.results, grid.pairs);
	writeFileSync(join(outDir, 'loopers.md'), looperMd);
	process.stdout.write(looperMd);
	process.exit(0);
}

const results = runGrid(SCENARIOS, seeds);

writeFileSync(
	join(outDir, 'results.json'),
	JSON.stringify(results.map((r) => ({ scenario: r.scenario, seed: r.seed, metrics: r.metrics })), null, 2)
);

for (const r of results.filter((x) => x.seed === 1)) {
	const header = Object.keys(r.series[0] ?? {}).join(',');
	const rows = r.series.map((d) => Object.values(d).join(','));
	writeFileSync(join(outDir, `${r.scenario}.csv`), [header, ...rows].join('\n'));
}

const summary = [markdownSummary(results, 'GSUSD peg-sim: scenario grid'), coverageTable(results)].join('\n');
writeFileSync(join(outDir, 'summary.md'), summary);
// out/ is gitignored; the committed record lives beside the README, with the seeds and
// the git-tracked parameter defaults that produced it.
writeFileSync(
	join(__dirname, '..', 'RESULTS.md'),
	[`<!-- generated by \`npx nx grid peg-sim\`; seeds ${seeds.join(',')}; do not edit -->`, '', summary].join('\n')
);
process.stdout.write(summary);
// vite-node keeps the event loop alive after the script returns; exit explicitly so
// `nx grid peg-sim` completes rather than hanging with the report already written.
process.exit(0);
