#!/usr/bin/env python3
"""
Generate test vectors for StabilityModule._rpow.

StabilityModule uses a MakerDAO-style `_rpow(x, n)` that computes `x^n / 1e18`
via exponentiation-by-squaring with fixed-point (1e18) half-up rounding. This
script produces a reference table computed in arbitrary-precision arithmetic
via mpmath, which the Solidity differential test asserts `_rpow` matches
within a small tolerance.

Run:
    pip install mpmath
    python3 contracts/tools/generate_rpow_vectors.py

The script prints a Solidity array literal that can be pasted into
contracts/test-foundry/fuzz/Rpow.differential.t.sol.
"""

from mpmath import mp, mpf, power

# 60 decimal digits of working precision — far more than the 18 we need.
mp.dps = 60

PRECISION = mpf(10) ** 18
SECONDS_PER_YEAR = 365 * 24 * 3600  # 31_536_000


def per_second(annual_bps: int) -> int:
    """Matches StabilityModule._annualToPerSecond (linear approximation)."""
    return int(PRECISION) + (annual_bps * int(PRECISION)) // (10_000 * SECONDS_PER_YEAR)


def rpow_reference(x_int: int, n: int) -> int:
    """Compute x^n / 1e18 with half-up rounding, matching _rpow semantics.

    _rpow computes x^n where each multiplication re-scales by 1e18. The final
    result is the fixed-point value of (x / 1e18) ^ n, in 1e18 units.
    """
    x = mpf(x_int) / PRECISION
    result = power(x, n)  # in natural units
    scaled = result * PRECISION  # back to 1e18 fixed-point
    # Half-up rounding to match `_rpow`'s behaviour.
    return int(scaled + mpf("0.5"))


def main() -> None:
    # Curated set of (annual_bps, elapsed_seconds) representative of expected
    # vault usage: low/mid/high rates, short/medium/long elapsed intervals.
    cases = [
        (0,    0),
        (0,    31_536_000),                 # 1 year, zero rate — identity
        (100,  0),                          # 1% APR, no time
        (100,  3600),                       # 1% APR, 1 hour
        (100,  86_400),                     # 1% APR, 1 day
        (200,  31_536_000),                 # 2% APR, 1 year
        (200,  31_536_000 * 5),             # 2% APR, 5 years
        (500,  31_536_000),                 # 5% APR, 1 year
        (1000, 31_536_000),                 # 10% APR, 1 year
        (1000, 31_536_000 * 3),             # 10% APR, 3 years
        (5000, 31_536_000),                 # 50% APR (max), 1 year
        (5000, 31_536_000 * 2),             # 50% APR, 2 years
        # Odd elapsed times: an odd exponent starts the product from x itself, a
        # branch the even cases above never take.
        (200,  1),                          # 2% APR, 1 second
        (100,  3601),                       # 1% APR, 1 hour and a second
        (200,  86_399),                     # 2% APR, 1 day less a second
        (200,  31_535_999),                 # 2% APR, 1 year less a second
        (1000, 31_535_999),                 # 10% APR, 1 year less a second
        (5000, 31_535_999),                 # 50% APR (max), 1 year less a second
        (5000, 63_071_999),                 # 50% APR, 2 years less a second
    ]

    print("// Auto-generated by contracts/tools/generate_rpow_vectors.py")
    print("// Do not edit by hand. Regenerate after any _rpow change.")
    print()
    print("struct RpowVector {")
    print("    uint256 perSecondRate;   // x in _rpow(x, n)")
    print("    uint256 elapsedSeconds;  // n in _rpow(x, n)")
    print("    uint256 expected;        // reference value, 1e18 fixed-point")
    print("}")
    print()
    print("function _vectors() internal pure returns (RpowVector[] memory v) {")
    print(f"    v = new RpowVector[]({len(cases)});")
    for i, (bps, elapsed) in enumerate(cases):
        x = per_second(bps)
        expected = rpow_reference(x, elapsed) if elapsed > 0 else int(PRECISION)
        print(
            f"    v[{i}] = RpowVector({{perSecondRate: {x}, "
            f"elapsedSeconds: {elapsed}, expected: {expected}}}); "
            f"// {bps} bps APR, {elapsed}s"
        )
    print("}")


if __name__ == "__main__":
    main()
